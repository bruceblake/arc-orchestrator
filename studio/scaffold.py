"""A Godot 4 graybox starter for the prison-escape project.

What this writes is deliberately small and deliberately CODE. The level is
built by a script from one table of dimensions rather than authored as a
.tscn, for three reasons:

  * The phase-1 gate measures Bucket A. A level built from named constants can
    be MEASURED by raycast (tools/measure.gd) and compared against the target,
    which is the difference between "the corridor is 2.4m" and "someone says
    the corridor is 2.4m".
  * A dimension change in graybox is the whole point of graybox. Editing one
    constant and re-measuring is a ten-second loop; dragging boxes in an
    editor is not, and neither is a model editing a binary-ish scene file.
  * Generated .tscn files are the most fragile thing an agent can write. One
    table of floats is not.

The scaffold is a STARTING POINT for phase 1, not a game. It has no netcode,
no routine, no suspicion, no contraband — those are what the fleet builds.
"""
