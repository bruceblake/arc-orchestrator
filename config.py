def harness_bin(harness):
    """The executable a harness runs as, for doctor checks and argv[0]."""
    if harness == "dsh":
        return dsh_bin()
    if harness == "reasonix":
        return reasonix_bin()
    if harness == "claude":
        return claude_bin()
    if harness == "codex":
        return codex_bin()
    if harness == "gemini":
        return gemini_bin()
    if harness == "cursor":
        return cursor_bin()
    if harness == "agy":
        return agy_bin()
