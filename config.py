def harness_limit(harness):
    """Max concurrent processes for a HARNESS, across every model it serves."""
    override = os.getenv(f"ARC_HARNESS_LIMIT_{harness.upper()}")
    if override:
        try:
            return max(1, int(override))
        except ValueError:
            pass
    return _HARNESS_CAP.get(harness, 8)


# A slot held back from BATCH work so interactive work always has somewhere to
# land. Without it a chat reply queues behind a full fleet and the human waits
# twenty minutes for a planner that is working perfectly.
#
# Reserved ONLY on the planner model, and only while that leaves batch at least
# two slots. Applying it to every model is wrong: it once took GLM and DeepSeek
# from 2 to 1 — halving fleet throughput to protect a path batch work never
# uses. With GLM's cap pinned at 4 (`_DRIVER_CAP_PIN`, operator directive
# 2026-09-15), batch callers see 4 - 1 = 3 and interactive callers the full 4;
# the MIN_BATCH_SLOTS guard only makes the reserve inert again if the cap ever
# falls to 2 (2 - 1 < 2 leaves batch too little). ARC_INTERACTIVE_RESERVE=0
# hands batch the fourth slot too when nobody is chatting. The cost of a
# reserve should fall on the one model chat actually uses, and only when it
# can afford to give.
INTERACTIVE_RESERVE = int(os.getenv("ARC_INTERACTIVE_RESERVE", "1"))
MIN_BATCH_SLOTS = 2


def _apply_reserve(model, cap, interactive):
    """`cap` for interactive callers; one fewer for batch, where it is affordable."""
    if interactive or model != PLANNER_MODEL:
        return cap
    if cap - INTERACTIVE_RESERVE < MIN_BATCH_SLOTS:
        return cap          # too small to give one away
    return cap - INTERACTIVE_RESERVE


def driver_limit(model, interactive=False):
    """Max concurrent harness instances for a model.

    Interactive callers see the full measured cap; batch callers see one fewer
    (INTERACTIVE_RESERVE), so a chat is never stuck behind a full fleet. Never
    returns less than 1 — reserving a slot must not make a model unusable.
    """
    override = os.getenv(f"ARC_DRIVER_LIMIT_{MODEL_FAMILY[model].upper().replace('-', '_')}")
    if override:
        try:
            return _apply_reserve(model, int(override), interactive)
        except ValueError:
            pass
    return _apply_reserve(model, _MODEL_DRIVER_CAP[model], interactive)

# --- graph admission control ------------------------------------------------
# Bounded admission (graph.py max_in_flight) stops a run from starting every
# ready task at once: work started past the real ceilings never ran — it
# queued inside drivers._lease_acquire holding a worktree and a DB row. The
# default is the total harness capacity, which exceeds the root count of every
# taskfile seen so far, so unconfigured runs behave exactly as before.
def max_tasks_in_flight():
    """Max graph nodes executing at once (ARC_MAX_TASKS_IN_FLIGHT)."""
    override = os.getenv("ARC_MAX_TASKS_IN_FLIGHT")
    if override:
        try:
            return max(1, int(override))
        except ValueError:
            pass
    return sum(harness_limit(h) for h in set(MODEL_HARNESS.values()))

