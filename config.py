def dsh_bin():
    """The dsh CLI binary (DeepSeek's harness, npm-installed 2026-09-12).

    npm's global bin is not on every shell's PATH (the service/shell that
    spawns harnesses may not be a login shell), so prefer the recorded install
    location over a bare name that would fail to exec with FileNotFoundError.
    """
    found = shutil.which(os.getenv("ARC_DSH_BIN", "dsh"))
    return found or str(Path.home() / ".local" / "opt" / "node" / "bin" / "dsh")


def reasonix_bin():
    """The reasonix CLI binary (npm `reasonix`, installed 2026-09-13).

    Same PATH caveat as dsh_bin: the service that spawns harnesses is not a
    login shell, so fall back to the npm prefix the operator installs into.
    """
    found = shutil.which(os.getenv("ARC_REASONIX_BIN", "reasonix"))
    return found or str(Path.home() / ".local" / "opt" / "node" / "bin" / "reasonix")


def _npm_bin(name, env_var):
    """A CLI installed by npm -g, found the way dsh_bin/reasonix_bin are.

    npm's global bin is not on every shell's PATH — the service or shell that
    spawns a harness is not a login shell — so a bare name would fail to exec
    with FileNotFoundError. Prefer PATH, fall back to the npm prefix.
    """
    found = shutil.which(os.getenv(env_var, name))
    return found or str(Path.home() / ".local" / "opt" / "node" / "bin" / name)


