# The per-MODEL caps above are the ARC API's ceiling. They are not the only
# ceiling: every opencode-backed model shares ONE local harness, and that
# harness serialises through a single ~240MB sqlite db in
# ~/.local/share/opencode. Since 2026-09-16 (task opencode-serve-only) the
# opencode harness is a PERSISTENT `opencode serve` server — ONE process per
# orchestrator reaching that store, with one session per run — rather than a
# fresh `opencode run` spawn per attempt. The cap VALUES below do not change in
# that switch (it is a transport change, not a capacity one); what changes is
# that the pool now bounds how many CONCURRENT SESSIONS the one server serves,
# and the cliff below was measured on the retired per-attempt spawn. On the
# two-model fleet (2026-09-12) only GLM-5.3
# runs opencode — DeepSeek moved to its own `reasonix` harness (2026-09-13,
# replacing `dsh`) — so the opencode pool sees GLM's 4 driver slots (pinned at
# the account budget by `_DRIVER_CAP_PIN` above) against
# the harness's cap of 5. The retired three-model fleet put
# GLM 4 + DeepSeek 5 + gpt-oss 5 = 14 concurrent opencode processes against
# it, and measured on this machine (identical prompt, warm cache):
#
#     3 concurrent   3/3 ok
#     4 concurrent   4/4 ok
#     5 concurrent   5/5 ok
#     6 concurrent   4/6 ok
#    10 concurrent   4/10 ok
#
# Past 5 it fails fast with an empty stderr, which the fleet logged as
# "opencode exited 1: " and retried four times per task — burning the retry
# ladder on self-inflicted contention and blaming the provider for it.
# dsh (added 2026-09-12) keeps its state as per-profile JSON files under
# $DSH_HOME — no central store like opencode's sqlite — so it gets no measured
# cliff yet; 5 mirrors opencode until a load test says otherwise. reasonix
# (2026-09-13) likewise keeps per-workspace session files under its home. Its
# load test ran 2026-09-14 (concurrent one-shot runs, warm cache, DeepSeek on
# an account cap of 10):
#
#     3 concurrent   3/3 ok
#     6 concurrent   6/6 ok
#     7 concurrent   7/7 ok
#
# No empty-output failures and no ARC capacity rejections — no local
# contention anywhere up to 7, unlike opencode's sqlite cliff at 6. The pool
# is 10 (the account ceiling; operator directive 2026-09-24). If ARC 400s
# reappear under a full reasonix pool, ARC_HARNESS_LIMIT_REASONIX is the knob.
# ("kimi" stays in _SESSIONS_PER_PROCESS only so a historical transcript's
